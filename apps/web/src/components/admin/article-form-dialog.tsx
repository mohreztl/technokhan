'use client';

import * as React from 'react';
import { useForm } from 'react-hook-form';
import { z } from 'zod';
import { toast } from 'sonner';
import { adminArticleSchema } from '@technokhan/shared';
import type { AdminArticle, AdminArticleSummary } from '@technokhan/shared';
import { ResponsiveDialog } from '@/components/ui/responsive-dialog';
import { Button } from '@/components/ui/button';
import { Checkbox } from '@/components/ui/checkbox';
import { Input } from '@/components/ui/input';
import { Textarea } from '@/components/ui/textarea';
import { useAdminArticle, useAdminMutations } from '@/lib/hooks/use-admin';
import { ImagePreviewStrip, ImageUploadButton } from './image-upload';
import { formResolver, joinLines, linesField, optionalText } from './form-utils';

const base = adminArticleSchema.shape;

/** `adminArticleSchema` with input-friendly fields (empty slug → generated by the API). */
export const articleFormSchema = adminArticleSchema
  .extend({
    slug: z
      .string()
      .trim()
      .max(160)
      .refine((v) => v === '' || /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(v), {
        message: 'اسلاگ فقط می‌تواند شامل حروف انگلیسی کوچک، عدد و خط تیره باشد',
      })
      .default(''),
    excerpt: optionalText(base.excerpt),
    coverImage: z.string().trim().default(''),
    author: optionalText(base.author),
    tags: linesField(z.array(z.string()).default([])),
  })
  .transform((v) => ({
    ...v,
    slug: v.slug || undefined,
    coverImage: v.coverImage || null,
  }));

export type ArticleFormOutput = z.output<typeof articleFormSchema>;

export interface ArticleFormValues {
  title: string;
  slug: string;
  category: string;
  excerpt: string;
  content: string;
  coverImage: string;
  tags: string;
  author: string;
  isActive: boolean;
}

function toValues(a?: AdminArticle | AdminArticleSummary | null): ArticleFormValues {
  return {
    title: a?.title ?? '',
    slug: a?.slug ?? '',
    category: a?.category ?? 'دانش فنی',
    excerpt: a?.excerpt ?? '',
    content: a && 'content' in a ? a.content : '',
    coverImage: a?.coverImage ?? '',
    tags: joinLines(a?.tags),
    author: a?.author ?? '',
    isActive: a?.isActive ?? true,
  };
}

export interface ArticleFormDialogProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  /** Editing target; `null` / `undefined` creates a new article. */
  article?: AdminArticleSummary | null;
  onSaved?: (article: AdminArticle) => void;
}

export function ArticleFormDialog({ open, onOpenChange, article, onSaved }: ArticleFormDialogProps) {
  const { createArticle, updateArticle } = useAdminMutations();
  const formId = React.useId();
  const isEdit = Boolean(article);
  const busy = createArticle.isPending || updateArticle.isPending;

  // the list endpoint omits the heavy content column — fetch the full record for editing
  const { data: full, isLoading: loadingFull } = useAdminArticle(open && article ? article.id : undefined);

  const {
    register,
    handleSubmit,
    reset,
    watch,
    setValue,
    formState: { errors },
  } = useForm<ArticleFormValues, unknown, ArticleFormOutput>({
    resolver: formResolver<ArticleFormValues, ArticleFormOutput>(articleFormSchema),
    defaultValues: toValues(article),
  });

  React.useEffect(() => {
    if (open) reset(toValues(full ?? article));
  }, [open, article, full, reset]);

  const coverImage = watch('coverImage') ?? '';

  const submit = async (out: ArticleFormOutput) => {
    const patch: Partial<AdminArticle> = {
      title: out.title,
      slug: out.slug,
      category: out.category,
      excerpt: out.excerpt,
      content: out.content,
      coverImage: out.coverImage,
      tags: out.tags,
      author: out.author,
      isActive: out.isActive,
    };
    try {
      const saved = article
        ? await updateArticle.mutateAsync({ id: article.id, patch })
        : await createArticle.mutateAsync(patch);
      toast.success(article ? 'مقاله به‌روزرسانی شد' : 'مقاله جدید ثبت شد', { description: saved.title });
      onSaved?.(saved);
      onOpenChange(false);
    } catch (e) {
      toast.error('ذخیرهٔ مقاله ناموفق بود', { description: e instanceof Error ? e.message : undefined });
    }
  };

  return (
    <ResponsiveDialog
      initialSnap={0.9}
      open={open}
      onOpenChange={(o) => {
        if (busy && !o) return;
        onOpenChange(o);
      }}
      title={isEdit ? 'ویرایش مقاله' : 'مقاله جدید'}
      description={isEdit ? article?.title : 'اطلاعات مقاله را وارد کنید؛ اسلاگ خالی به‌صورت خودکار ساخته می‌شود.'}
      snapPoints={[0.92]}
      dismissible={!busy}
      desktopClassName="max-w-2xl"
      footer={
        <div className="grid grid-cols-2 gap-3">
          <Button type="button" variant="outline" onClick={() => onOpenChange(false)} disabled={busy}>
            انصراف
          </Button>
          <Button type="submit" form={formId} loading={busy} loadingText="در حال ذخیره…" disabled={isEdit && loadingFull}>
            {isEdit ? 'ذخیره تغییرات' : 'ثبت مقاله'}
          </Button>
        </div>
      }
    >
      <form id={formId} onSubmit={handleSubmit(submit)} noValidate className="grid gap-4 pt-1 sm:grid-cols-2">
        <div className="sm:col-span-2">
          <Input label="عنوان مقاله" error={errors.title?.message} autoComplete="off" {...register('title')} />
        </div>
        <Input
          label="اسلاگ (اختیاری؛ انگلیسی)"
          dir="ltr"
          className="text-start"
          placeholder="gan-charger-guide"
          error={errors.slug?.message}
          {...register('slug')}
        />
        <Input label="دسته‌بندی" error={errors.category?.message} {...register('category')} />
        <div className="sm:col-span-2">
          <Textarea label="خلاصه (اختیاری)" className="min-h-[64px]" error={errors.excerpt?.message} {...register('excerpt')} />
        </div>
        <div className="sm:col-span-2">
          <div className="mb-2 flex items-center justify-between gap-2">
            <span className="text-sm font-medium">تصویر کاور</span>
            <ImageUploadButton onUploaded={(url) => setValue('coverImage', url, { shouldDirty: true })} label="آپلود تصویر از سیستم" />
          </div>
          {coverImage ? (
            <div className="mb-2 flex items-start gap-2">
              <ImagePreviewStrip images={[coverImage]} size={96} />
              <Button type="button" variant="ghost" size="sm" onClick={() => setValue('coverImage', '', { shouldDirty: true })}>
                حذف کاور
              </Button>
            </div>
          ) : null}
          <Input
            label="مسیر تصویر کاور"
            dir="ltr"
            className="text-start text-sm"
            placeholder="https://… یا /images/…"
            error={errors.coverImage?.message}
            {...register('coverImage')}
          />
        </div>
        <div className="sm:col-span-2">
          <Textarea
            label={isEdit && loadingFull ? 'متن مقاله (در حال بارگذاری…)' : 'متن مقاله (HTML یا متن ساده)'}
            className="min-h-[220px]"
            error={errors.content?.message}
            disabled={isEdit && loadingFull}
            {...register('content')}
          />
        </div>
        <Textarea label="برچسب‌ها (هر مورد در یک خط)" className="min-h-[88px]" error={errors.tags?.message} {...register('tags')} />
        <div className="flex flex-col gap-4">
          <Input label="نویسنده (اختیاری)" error={errors.author?.message} {...register('author')} />
          <Checkbox label="منتشر شده (قابل مشاهده در مجله)" {...register('isActive')} />
        </div>
      </form>
    </ResponsiveDialog>
  );
}
